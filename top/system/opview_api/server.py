"""
opview app API on webrtcd's HTTP server (port 5001), next to its /stream: settings, drives, playback, downloads.
Paths and JSON follow dashy (dragonpilot's web UI, port 5088) so the same app works on both; TOP's additions are marked.

Pairing: everything here except /api/init needs the device's pairing code (OpviewPairingCode, shown with the opview
toggle in TOP settings), as the X-Opview-Token header or ?token= (video players can't set headers).
/stream (the live view) stays open as before for the existing opview app.
"""
import asyncio
import hmac
import json
import os
from functools import partial

from aiohttp import web

from openpilot.common.params import Params
from openpilot.common.swaglog import cloudlog
from openpilot.system.hardware import HARDWARE
from openpilot.system.ui.lib.multilang import tr_noop
from openpilot.top.system.opview_api import routes
from openpilot.top.system.opview_api.pairing import pairing_code
from openpilot.top.system.opview_api.i18n import Translator, resolve_language
from openpilot.top.system.opview_api.settings import SettingError, SettingsAPI

API_VERSION = 1
TOKEN_HEADER = "X-Opview-Token"
OPEN_PATHS = {"/api/init"}
PROTECTED_PREFIXES = ("/api/", "/media/", "/download/")
# big files: not while driving, loggerd is writing to the same disk
ONROAD_BLOCKED_PREFIXES = ("/download/",)
ONROAD_BLOCKED_SUFFIXES = (".hevc", ".zst")
ONROAD_TEXT = tr_noop("Not available while driving.")

PARAMS_KEY = web.AppKey("opview_params", Params)
SETTINGS_KEY = web.AppKey("opview_settings", SettingsAPI)
ROOT_KEY = web.AppKey("opview_root", str)


def _json_error(status: int, message: str, **extra) -> web.Response:
  return web.json_response({"error": message, **extra}, status=status)


def _translator(request: web.Request) -> Translator:
  return Translator(resolve_language(request.query.get("lang"), request.headers.get("Accept-Language")))


@web.middleware
async def opview_auth_middleware(request: web.Request, handler):
  path = request.path
  if path in OPEN_PATHS or not path.startswith(PROTECTED_PREFIXES):
    return await handler(request)

  params: Params = request.app[PARAMS_KEY]
  token = request.headers.get(TOKEN_HEADER) or request.query.get("token") or ""
  if not hmac.compare_digest(token.encode(), pairing_code(params).encode()):
    return _json_error(401, "pairing code required", code="unpaired")

  if params.get_bool("IsOnroad") and (path.startswith(ONROAD_BLOCKED_PREFIXES) or path.endswith(ONROAD_BLOCKED_SUFFIXES)):
    return _json_error(409, _translator(request)(ONROAD_TEXT), code="onroad")
  return await handler(request)


def hud_settings(params: Params) -> dict:
  """The device's display settings the app's live view draws TOP's HUD with (not sensitive: no pairing needed)"""
  try:
    speed_limit_mode = int(params.get("SpeedLimitMode", return_default=True) or 0)
  except (TypeError, ValueError):
    speed_limit_mode = 0
  return {
    "is_metric": params.get_bool("IsMetric"),
    "speed_limit_mode": speed_limit_mode,
    "tim_signals": params.get_bool("TimSignals"),
    "personality_wheel": params.get_bool("DrivingPersonalitiesUIWheel"),
  }


async def init_api(request: web.Request) -> web.Response:
  params: Params = request.app[PARAMS_KEY]
  return web.json_response({
    "isOffroad": not params.get_bool("IsOnroad"),
    "top": {"api": API_VERSION, "pairing": True, "device_type": HARDWARE.get_device_type(),
            "version": params.get("Version") or "", "dongle_id": params.get("DongleId") or "",
            "hud": hud_settings(params)},
  })


async def settings_api(request: web.Request) -> web.Response:
  api: SettingsAPI = request.app[SETTINGS_KEY]
  tr = _translator(request)
  # the car list is generated by a subprocess the first time
  return web.json_response(await asyncio.get_running_loop().run_in_executor(None, partial(api.schema, tr)))


async def get_param_api(request: web.Request) -> web.Response:
  api: SettingsAPI = request.app[SETTINGS_KEY]
  key = request.match_info["param_name"]
  try:
    return web.json_response({"key": key, "value": api.get(key)})
  except SettingError as e:
    return _json_error(e.status, e.message)


async def save_param_api(request: web.Request) -> web.Response:
  api: SettingsAPI = request.app[SETTINGS_KEY]
  key = request.match_info["param_name"]
  try:
    data = await request.json()
  except json.JSONDecodeError:
    return _json_error(400, "body must be JSON")
  if not isinstance(data, dict) or "value" not in data:
    return _json_error(400, "value is required in body")
  try:
    value = await asyncio.get_running_loop().run_in_executor(None, api.put, key, data["value"])
  except SettingError as e:
    return _json_error(e.status, _translator(request)(e.message) if e.status == 409 else e.message)
  cloudlog.info(f"opview: {key} = {value!r}")
  return web.json_response({"status": "success", "key": key, "value": value})


async def files_api(request: web.Request) -> web.Response:
  result = routes.list_files(request.query.get("path", "/"), request.app[ROOT_KEY])
  if result is None:
    return _json_error(404, "Invalid or Not Found Path")
  return web.json_response(result)


async def routes_api(request: web.Request) -> web.Response:
  root = request.app[ROOT_KEY]
  return web.json_response({"routes": await asyncio.get_running_loop().run_in_executor(None, routes.list_routes, root)})


async def manifest_api(request: web.Request) -> web.Response:
  root = request.app[ROOT_KEY]
  token = request.headers.get(TOKEN_HEADER) or request.query.get("token")
  if route := request.query.get("route"):
    manifest = routes.route_manifest(route, root, token)
    if manifest is None:
      return _json_error(404, "route not found")
  else:
    file = request.query.get("file", "").lstrip("/")
    if not file or routes.safe_path(file, root) is None:
      return _json_error(400, "file parameter is required")
    manifest = routes.file_manifest(file, token)
  return web.Response(text=manifest, content_type="application/vnd.apple.mpegurl")


async def download_api(request: web.Request) -> web.StreamResponse:
  """like /media, as an attachment (the phone saves it instead of playing it)"""
  root = request.app[ROOT_KEY]
  path = routes.safe_path(request.match_info["path"], root)
  if path is None or not os.path.isfile(path):
    return _json_error(404, "file not found")
  rel = os.path.relpath(path, root)
  name = rel.replace(os.sep, "_")  # 0000002a--b4c8e1f2d3--7_fcamera.hevc
  return web.FileResponse(path, headers={"Content-Disposition": f'attachment; filename="{name}"'})


def setup(app: web.Application, params: Params | None = None, root: str | None = None) -> None:
  """Add the opview API to webrtcd's aiohttp app"""
  params = params or Params()
  root = os.path.realpath(root or routes.log_root())
  os.makedirs(root, exist_ok=True)
  pairing_code(params)

  app[PARAMS_KEY] = params
  app[SETTINGS_KEY] = SettingsAPI(params)
  app[ROOT_KEY] = root
  app.middlewares.append(opview_auth_middleware)

  app.router.add_get("/api/init", init_api)
  app.router.add_get("/api/settings", settings_api)
  app.router.add_get("/api/settings/params/{param_name}", get_param_api)
  app.router.add_post("/api/settings/params/{param_name}", save_param_api)
  app.router.add_get("/api/files", files_api)
  app.router.add_get("/api/routes", routes_api)  # TOP
  app.router.add_get("/api/manifest.m3u8", manifest_api)
  app.router.add_static("/media", path=root, name="opview_media", show_index=False, follow_symlinks=False)
  app.router.add_get("/download/{path:.+}", download_api)
